// Regenerate approximate travel-area centers from the checked-in public facility dataset.
import { readFile, readdir, writeFile } from 'node:fs/promises';

const resourceDir = new URL('../../backend/src/main/resources/', import.meta.url);
const filename = (await readdir(resourceDir)).find((name) => name.includes('문화시설') && name.endsWith('.csv'));
if (!filename) throw new Error('Missing facility dataset');
const csv = await readFile(new URL(filename, resourceDir), 'utf8');
function parseCsv(text) {
    const rows = []; let row = []; let cell = ''; let quoted = false;
    for (let i = 0; i < text.length; i++) {
        const char = text[i];
        if (char === '"') {
            if (quoted && text[i + 1] === '"') { cell += '"'; i++; }
            else quoted = !quoted;
        } else if (!quoted && (char === ',' || char === '\n')) {
            row.push(cell.replace(/\r$/, '')); cell = '';
            if (char === '\n') { rows.push(row); row = []; }
        } else cell += char;
    }
    if (cell || row.length) { row.push(cell); rows.push(row); }
    return rows;
}
const areaCodes = { 서울특별시: '1', 인천광역시: '2', 대전광역시: '3', 대구광역시: '4', 광주광역시: '5', 부산광역시: '6', 울산광역시: '7', 세종특별자치시: '8', 경기도: '31', 강원도: '32', 강원특별자치도: '32', 충청북도: '33', 충청남도: '34', 경상북도: '35', 경상남도: '36', 전라북도: '37', 전북특별자치도: '37', 전라남도: '38', 제주특별자치도: '39' };
const [header, ...rows] = parseCsv(csv.replace(/^\uFEFF/, ''));
const columns = ['시도 명칭', '시군구 명칭', '위도', '경도'].map((name) => header.indexOf(name));
if (columns.includes(-1)) throw new Error('Unexpected dataset columns');
const grouped = new Map();
for (const row of rows) {
    const [area, district, lat, lon] = columns.map((index) => row[index]);
    const code = areaCodes[area];
    const latitude = Number(lat), longitude = Number(lon);
    if (!code || !district || latitude < 33 || latitude > 39 || longitude < 124 || longitude > 132) continue;
    const key = `${code}:${district.trim().split(/\s+/)[0]}`;
    if (!grouped.has(key)) grouped.set(key, []);
    grouped.get(key).push([latitude, longitude]);
}
const median = (values) => { values.sort((a, b) => a - b); return Number(values[Math.floor(values.length / 2)].toFixed(5)); };
const centers = Object.fromEntries([...grouped].sort().map(([key, points]) => [key, [median(points.map((p) => p[0])), median(points.map((p) => p[1]))]]));
const output = `// Generated by scripts/generate-district-centers.mjs from ${filename}\n// Median facility coordinates: approximate travel centers, not administrative boundaries.\nexport const districtCenters: Record<string, [number, number]> = {\n${Object.entries(centers).map(([key, value]) => `    ${JSON.stringify(key)}: ${JSON.stringify(value)},`).join('\n')}\n};\n`;
await writeFile(new URL('../src/features/course/utils/districtCenters.ts', import.meta.url), output);
console.log(`Generated ${grouped.size} district centers`);
